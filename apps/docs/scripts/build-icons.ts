// Writes src/registry/icons/__<library>__.ts with the icons the registry's
// placeholders use, so the docs' IconPlaceholder only loads those. From
// shadcn/ui 0e5b2e6, apps/v4/scripts/build-icons.ts (MIT).
import { readdir, readFile, writeFile } from "node:fs/promises"

import {
  iconLibraries,
  iconLibraryNames,
  iconPlaceholderNames
} from "@solid-ui/registry/icons"

const registryDir = new URL("../src/registry/", import.meta.url)
const files = (await readdir(registryDir, { recursive: true }))
  .filter((file) => file.endsWith(".tsx"))
  .sort()

const sources = await Promise.all(
  files.map(async (file) => {
    const source = await readFile(new URL(file, registryDir), "utf8")
    return { file, source }
  })
)

for (const library of iconLibraryNames) {
  const icons = new Set<string>()
  for (const { file, source } of sources) {
    try {
      for (const icon of iconPlaceholderNames(source, library)) icons.add(icon)
    } catch (error) {
      throw new Error(`${(error as Error).message} in src/registry/${file}`, {
        cause: error
      })
    }
  }
  // An import, not a re-export: vite-plugin-lucide-preprocess splits imports
  // into one module per icon.
  const names = [...icons].sort().join(",\n  ")
  const content = `// Generated by scripts/build-icons.ts from the registry's IconPlaceholders.
import {
  ${names}
} from "${iconLibraries[library].package}"

export {
  ${names}
}
`
  const target = new URL(`icons/__${library}__.ts`, registryDir)
  const current = await readFile(target, "utf8").catch(() => "")
  if (current !== content) await writeFile(target, content)
  console.log(
    `Icons built: ${icons.size} ${iconLibraries[library].title} icons.`
  )
}
