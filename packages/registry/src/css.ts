import { encodePreset, type Preset } from "./preset/codec.ts"
import { fontPackage, fontStack, presetFonts } from "./theme/fonts.ts"
import { resolvePresetTheme } from "./theme/index.ts"

// Tokens the theme resolver adds for the docs site only. Components don't
// use them, so installed themes leave them out, as shadcn/ui does.
const DOCS_ONLY_TOKENS = new Set([
  "destructive-foreground",
  "surface",
  "surface-foreground",
  "code",
  "code-foreground",
  "code-highlight",
  "code-number",
  "selection",
  "selection-foreground",
  "radius"
])

// Multiples of --radius, from shadcn/ui 055aa6b,
// packages/registry/src/updaters/update-css-vars.ts (MIT). The Create preview
// uses the same scale.
const RADIUS_SCALE = {
  sm: "calc(var(--radius) * 0.6)",
  md: "calc(var(--radius) * 0.8)",
  lg: "var(--radius)",
  xl: "calc(var(--radius) * 1.4)",
  "2xl": "calc(var(--radius) * 1.8)",
  "3xl": "calc(var(--radius) * 2.2)",
  "4xl": "calc(var(--radius) * 2.6)"
}

function themeTokens(colors: Record<string, string>) {
  return Object.entries(colors).filter(([key]) => !DOCS_ONLY_TOKENS.has(key))
}

function block(selector: string, declarations: [string, string][]) {
  return `${selector} {\n${declarations
    .map(([property, value]) => `  ${property}: ${value};`)
    .join("\n")}\n}`
}

// The CSS variables and Tailwind theme mapping for a preset.
export function createThemeCss(preset: Preset): string {
  const theme = resolvePresetTheme(preset)
  const light = themeTokens(theme.light)
  const dark = themeTokens(theme.dark)
  const [bodyFont] = presetFonts(preset)

  return [
    block(":root", [
      ["--radius", theme.radius],
      ...light.map(([key, value]): [string, string] => [`--${key}`, value])
    ]),
    block(
      ".dark",
      dark.map(([key, value]): [string, string] => [`--${key}`, value])
    ),
    block("@theme inline", [
      ["--font-sans", fontStack(bodyFont!)],
      [
        "--font-heading",
        preset.fontHeading === "inherit"
          ? "var(--font-sans)"
          : fontStack(preset.fontHeading)
      ],
      ...light.map(([key]): [string, string] => [
        `--color-${key}`,
        `var(--${key})`
      ]),
      ...Object.entries(RADIUS_SCALE).map(([size, value]): [string, string] => [
        `--radius-${size}`,
        value
      ])
    ])
  ].join("\n\n")
}

// npm packages the stylesheet imports, besides Tailwind itself.
export function solidUiCssPackages(preset: Preset): string[] {
  return ["tw-animate-css", ...presetFonts(preset).map(fontPackage)]
}

export type SolidUiCssOptions = {
  preset: Preset
  // style-utilities.css from the registry, unchanged.
  utilitiesCss: string
  // The app stylesheet that imports solid-ui.css, named in the header.
  appCss?: string
}

// The solid-ui.css that `solidui-cli init` writes next to the app stylesheet.
export function createSolidUiCss({
  preset,
  utilitiesCss,
  appCss = "your app stylesheet"
}: SolidUiCssOptions): string {
  const header = `/*
 * Generated by solidui-cli from preset ${encodePreset(preset)} (style ${preset.style}).
 * Do not edit this file: \`npx solidui-cli init --force\` writes it again.
 * Put your own styles in ${appCss}.
 */`

  return `${[
    header,
    solidUiCssPackages(preset)
      .map((name) => `@import "${name}";`)
      .join("\n"),
    "@custom-variant dark (&:is(.dark *));",
    utilitiesCss.replace(/\r\n?/g, "\n").trim(),
    createThemeCss(preset),
    `@layer base {
  * {
    @apply border-border outline-ring/50;
  }
  body {
    @apply bg-background text-foreground;
  }
}`
  ].join("\n\n")}\n`
}
